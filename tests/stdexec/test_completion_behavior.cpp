/**
 * The then adaptor introduces set_error(std::exception_ptr) when its callable throws. However, the completion-behavior query for that error channel is still derived from the child. The child has no error completion whose behavior can establish affinity.
 * the error completion introduced by then actually occurs in the context of the child's value completion, but its completion-behavior metadata does not reflect that.
 * For the error channel, there are two possible sources:
- Errors forwarded from the predecessor.
- Errors generated by invoking the callable (including the exception converted to std::exception_ptr).
If the predecessor cannot send errors, the behavior of the generated error should inherit the predecessor's value-completion behavior.

More generally, the resulting error-channel behavior should account for both sources. It should be affine only when both possible sources are affine.

For your example, this would make the error channel affine, allowing __stays_put to succeed. continues_on would then preserve the receiver's get_start_scheduler property, and the inline scheduler could answer its completion-scheduler query.
 */
consteval bool test_stays_put() {
    using sndr_t = std::invoke_result_t<
        stdexec::then_t,
        stdexec::schedule_result_t<decltype(std::declval<exec::single_thread_context>().get_scheduler())>,
        Tests::Utils::Functors::NoOp<true, false, false>
    >;

    using start_scheduler_env_t = stdexec::prop<stdexec::get_start_scheduler_t, stdexec::run_loop::scheduler>;

    static_assert(stdexec::__sends<stdexec::set_value_t, sndr_t, start_scheduler_env_t>);

    static_assert(
        !stdexec::__completes_where_it_starts<stdexec::set_value_t, stdexec::env_of_t<sndr_t>, start_scheduler_env_t>);

    constexpr auto behavior = stdexec::__get_completion_behavior<stdexec::set_value_t, sndr_t, start_scheduler_env_t>();
    static_assert(behavior == stdexec::__completion_behavior::__asynchronous);

    static_assert(!stdexec::__stays_put_for<stdexec::set_value_t, sndr_t, start_scheduler_env_t>);

    return true;
}

static_assert(test_stays_put());

